const fs = require('fs'); const path = require('path');
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
module.exports = async ({ win }) => {
  const out = process.env.OUT_DIR; const js = (s) => win.webContents.executeJavaScript(s);
  const shot = async (n) => fs.writeFileSync(path.join(out, n), (await win.webContents.capturePage()).toPNG());
  let fails = 0;
  const check = (name, cond, info) => { console.log((cond ? 'PASS ' : 'FAIL ') + name + (cond ? '' : '  ' + JSON.stringify(info))); if (!cond) fails++; };
  const flagged = () => js(`[...document.querySelectorAll('.cm-spell-error')].map(e => e.textContent).join(',')`);
  const dictFile = path.join(require('electron').app.getPath('userData'), 'dictionary.txt');
  fs.writeFileSync(dictFile, '');
  win.setSize(1440, 900);
  const doc = ['Title: The Projectionist', 'Contact:', '    mae@orpheum.com', '', 'INT. KICHEN - DAY [[COLOR RED]]', '',
    "Mae recieve the pakage. She doesn't look up. Okafor waits. 35mm reels.", '', 'MAE OKAFOR', "Teh end. We're closing.", '',
    '/* Mispeled text in the boneyard is ignored */', '', '[[A notte to self]]', ''].join('\n');
  await js(`App.setDocument(${JSON.stringify(doc)}, null, 'spell.fountain'); App.cm.setCursor({line:0,ch:0})`); await sleep(1200);
  const f = (await flagged()).split(',');
  check('flags misspellings', ['KICHEN', 'recieve', 'pakage', 'Teh', 'notte'].every(w => f.includes(w)), f);
  check('ignores names, contractions, title keys, emails, color notes, numbers, boneyard',
    !['Mae', 'MAE', 'OKAFOR', 'Okafor', 'doesn', 'We', 'Contact', 'orpheum', 'COLOR', 'mm', 'Mispeled', 'Projectionist'].some(w => f.includes(w)), f);
  await shot('s1-underlines.png');
  await js(`cmd('spelling')`); await sleep(600);
  check('review starts at first word', (await js(`document.querySelector('.sp-context mark').textContent`)) === 'KICHEN');
  const sugg = await js(`[...document.querySelectorAll('.sp-sugg [data-s]')].map(b => b.dataset.s)`);
  check('KITCHEN suggested first, case-matched', sugg[0] === 'KITCHEN' && sugg.every(x => x === x.toUpperCase()), sugg);
  await js(`document.querySelector('[data-s="KITCHEN"]').click()`);
  check('editor selects the word', (await js(`App.cm.getSelection()`)) === 'KICHEN');
  await shot('s2-review.png');
  await js(`document.querySelector('[data-x=change]').click()`); await sleep(500);
  check('change applied', (await js(`App.cm.getLine(4)`)).startsWith('INT. KITCHEN - DAY'));
  check('moves to next word', (await js(`document.querySelector('.sp-context mark').textContent`)) === 'recieve');
  await js(`document.querySelector('[data-s="receive"]').click(); document.querySelector('[data-x=change]').click()`); await sleep(500);
  check('picked suggestion applied', (await js(`App.cm.getLine(6)`)).startsWith('Mae receive the'));
  await js(`document.querySelector('[data-x=ignore]').click()`); await sleep(400);
  check('ignore all skips pakage', (await js(`document.querySelector('.sp-context mark').textContent`)) === 'Teh');
  await js(`document.querySelector('[data-x=add]').click()`); await sleep(500);
  check('add to dictionary moves on', (await js(`document.querySelector('.sp-context mark').textContent`)) === 'notte');
  await js(`document.querySelector('[data-x=skip]').click()`); await sleep(400);
  check('done screen', await js(`!!document.querySelector('.sp-done')`));
  await js(`document.querySelector('[data-x=close]').click()`); await sleep(400);
  check('dialog closed', await js(`document.getElementById('modal-backdrop').hidden && !document.getElementById('modal-backdrop').classList.contains('spelling')`));
  const f2 = (await flagged()).split(',').filter(Boolean);
  check('underlines updated (only skipped word left)', f2.length === 1 && f2[0] === 'notte', f2);
  const dict = path.join(require('electron').app.getPath('userData'), 'dictionary.txt');
  check('personal dictionary saved', fs.existsSync(dict) && fs.readFileSync(dict, 'utf8').includes('Teh'));
  await js(`App.setDocument('INT. ROOM - DAY\\n\\nThe wierd light. A wierd sound. Wierd.\\n', null, 'x'); App.cm.setCursor({line:0,ch:0})`); await sleep(800);
  await js(`cmd('spelling')`); await sleep(600);
  check('change all offered', (await js(`document.querySelector('[data-x=all]').textContent`)) === 'Change all (3)');
  await js(`document.querySelector('[data-x=all]').click()`); await sleep(500);
  check('change all keeps case', (await js(`App.cm.getLine(2)`)) === 'The weird light. A weird sound. Weird.', await js(`App.cm.getLine(2)`));
  await js(`App.closeModal()`);
  await js(`App.setDocument('Teh recieve.\\n', null, 'x')`); await sleep(800);
  check('underlines on', (await flagged()).includes('recieve'));
  await js(`Spell.setEnabled(false)`); await sleep(200);
  check('toggle off removes underlines', (await flagged()) === '');
  await js(`Spell.setEnabled(true); cmd('title-page')`); await sleep(200);
  check('normal dialogs keep dim backdrop', await js(`!document.getElementById('modal-backdrop').classList.contains('spelling')`));
  await js(`App.closeModal()`);
  const errs = await js('window.__errs.filter(e => !e.includes("ResizeObserver"))');
  check('no renderer errors', errs.length === 0, errs);
  console.log(fails ? `SPELL: ${fails} failures` : 'SPELL: all passed');
};
